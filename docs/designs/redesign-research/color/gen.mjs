// Generates proposed-tokens.css (three tiers), roles.md (role table) and preview.html from tokens.mjs.
import fs from 'node:fs'
import { prim, light, dark, css, rampNames, rampSteps } from './tokens.mjs'
import { resolve } from './lib.mjs'
const v = k => `var(--${k.replace('.', '-')})`
const val = (T, role) => T[role].startsWith('mix:') ? (() => { const [, a, b, p] = T[role].split(':'); return `color-mix(in oklab, var(--${a}) ${p}%, var(--${b}))` })() : v(T[role])
const publicRoles = Object.keys(light).filter(r => !r.startsWith('ctaA') && !r.startsWith('vizA') )
const alias = { // existing shadcn names that simply point at a role
  'card-foreground': 'foreground', 'popover-foreground': 'foreground', 'secondary-foreground': 'foreground',
  'sidebar-foreground': 'foreground', 'sidebar-primary': 'brand', 'sidebar-accent': 'accent',
  'sidebar-accent-foreground': 'accent-foreground', 'sidebar-border': 'border', 'sidebar-ring': 'ring',
  'chart-1': 'viz-mastered', 'chart-2': 'viz-learning', 'chart-3': 'viz-progress', 'chart-4': 'viz-new', 'chart-5': 'viz-track',
  'streak-foreground': 'streak',
}
let out = '/* GENERATED by gen.mjs from tokens.mjs. Proposal only. */\n\n/* Tier 1: primitives. Components never use these directly. */\n:root {\n'
for (const ramp of rampNames) { for (const step of rampSteps[ramp]) out += `  --${ramp}-${step}: ${prim[`${ramp}.${step}`]}; /* ${resolve(prim[`${ramp}.${step}`]).hex} */\n`; out += '\n' }
out += '}\n\n/* Tier 2: semantic roles, light. */\n:root {\n  color-scheme: light;\n'
for (const r of publicRoles) out += `  --${r}: ${val(light, r)};\n`
out += `  --sidebar-primary-foreground: var(--neutral-0);\n`
for (const [a, r] of Object.entries(alias)) out += `  --${a}: var(--${r});\n`
out += '}\n\n/* Tier 2: semantic roles, dark (deep navy). */\n.dark {\n  color-scheme: dark;\n'
for (const r of publicRoles) out += `  --${r}: ${val(dark, r)};\n`
out += `  --sidebar-primary-foreground: var(--navy-950);\n`
out += '}\n\n/* Option A (blue call to action): replace the five --cta lines with these.\n   light: '
out += ['ctaA', 'ctaA-foreground', 'ctaA-hover', 'ctaA-active', 'ctaA-edge'].map(r => `--${r.replace('ctaA', 'cta')}: ${val(light, r)}`).join('; ') + '\n   dark:  '
out += ['ctaA', 'ctaA-foreground', 'ctaA-hover', 'ctaA-active', 'ctaA-edge'].map(r => `--${r.replace('ctaA', 'cta')}: ${val(dark, r)}`).join('; ') + '\n*/\n\n'
out += '/* Tier 3: expose roles to Tailwind as utilities (bg-hero, text-cta-foreground, ...). */\n@theme inline {\n'
for (const r of [...publicRoles, 'sidebar-primary-foreground', ...Object.keys(alias)]) out += `  --color-${r}: var(--${r});\n`
out += '}\n'
fs.writeFileSync(new URL('./proposed-tokens.css', import.meta.url), out)

// roles.md
const rows = ['| Role (CSS variable) | Light | Light value | Dark | Dark value |', '|---|---|---|---|---|']
for (const r of Object.keys(light)) {
  const l = css(light, r), d = css(dark, r)
  rows.push(`| \`--${r.replace('ctaA', 'cta (option A)').replace('vizA', 'viz (option A)')}\` | ${light[r].startsWith('mix') ? 'mix 14% hero-foreground into hero' : light[r]} | \`${l}\` ${resolve(l).hex} | ${dark[r].startsWith('mix') ? 'mix 14% hero-foreground into hero' : dark[r]} | \`${d}\` ${resolve(d).hex} |`)
}
fs.writeFileSync(new URL('./roles.md', import.meta.url), rows.join('\n') + '\n')

// preview.html: quick eyeball check of both themes and both CTA options
const sw = (T, r) => resolve(css(T, r)).hex
const panel = (name, T, opt) => {
  const c = opt === 'B' ? { fill: sw(T, 'cta'), fg: sw(T, 'cta-foreground'), edge: sw(T, 'cta-edge'), hero: sw(T, 'hero'), hfg: sw(T, 'hero-foreground'), hmu: sw(T, 'hero-muted-foreground'), chip: sw(T, 'hero-chip') }
    : { fill: sw(T, 'ctaA'), fg: sw(T, 'ctaA-foreground'), edge: sw(T, 'ctaA-edge'), hero: sw(T, 'hero-soft'), hfg: sw(T, 'foreground-strong'), hmu: sw(T, 'muted-foreground'), chip: sw(T, 'card') }
  return `<section style="background:${sw(T, 'background')};color:${sw(T, 'foreground')};padding:24px;font:16px/1.5 system-ui;width:560px">
  <div style="font-size:12px;color:${sw(T, 'muted-foreground')}">${name} / option ${opt}</div>
  <div style="background:${c.hero};color:${c.hfg};border-radius:16px;padding:24px;margin:8px 0 16px">
    <div style="font-size:14px;font-weight:600;color:${c.hmu}">Today</div>
    <div style="font-size:44px;font-weight:800;line-height:1.1">24 <span style="font-size:18px;font-weight:600">cards ready</span></div>
    <div style="color:${c.hmu};margin:4px 0 16px">About 4 minutes</div>
    <span style="background:${c.chip};padding:4px 10px;border-radius:8px;font-size:14px">16 Spanish</span>
    <div style="margin-top:16px"><button style="background:${c.fill};color:${c.fg};border:0;border-bottom:3px solid ${c.edge};border-radius:12px;padding:14px 40px;font:700 18px system-ui">Start review</button></div>
  </div>
  <div style="background:${sw(T, 'card')};border:1px solid ${sw(T, 'border')};border-radius:16px;padding:20px">
    <div style="color:${sw(T, 'foreground-strong')};font-weight:700;font-size:18px">Spanish Core 1000</div>
    <div style="color:${sw(T, 'muted-foreground')};font-size:14px">Last studied 2 hours ago</div>
    <div style="display:flex;height:12px;border-radius:99px;overflow:hidden;margin:14px 0 8px;gap:2px;background:${sw(T, 'card')}">
      <i style="width:22%;background:${sw(T, opt === 'B' ? 'viz-mastered' : 'vizA-mastered')}"></i><i style="width:30%;background:${sw(T, opt === 'B' ? 'viz-learning' : 'vizA-learning')}"></i><i style="flex:1;background:${sw(T, 'viz-new')}"></i></div>
    <span style="background:${sw(T, 'muted')};padding:3px 8px;border-radius:6px;font-size:14px">aprovechar</span>
    <span style="color:${sw(T, 'success')};font-weight:600;margin-left:8px">Goal met</span>
    <span style="color:${sw(T, 'warning')};font-weight:600;margin-left:8px">7 slipping</span>
    <span style="color:${sw(T, 'destructive')};font-weight:600;margin-left:8px">Error</span>
    <span style="color:${sw(T, 'streak')};font-weight:700;margin-left:8px">&#9650; 12 days</span>
    <a style="color:${sw(T, 'link')};margin-left:8px;text-decoration:underline">See all</a>
  </div></section>`
}
const ramps = rampNames.map(r => `<div style="display:flex">${rampSteps[r].map(s => `<div style="width:50px;height:34px;background:${resolve(prim[`${r}.${s}`]).hex};font:9px system-ui;color:${s >= 500 ? '#fff' : '#000'}">${r[0]}${s}</div>`).join('')}</div>`).join('')
fs.writeFileSync(new URL('./preview.html', import.meta.url), `<!doctype html><meta charset="utf-8"><title>Token preview</title><body style="margin:0;background:#888"><div style="display:grid;grid-template-columns:560px 560px;gap:0">${panel('light', light, 'B')}${panel('dark', dark, 'B')}${panel('light', light, 'A')}${panel('dark', dark, 'A')}</div>${ramps}</body>`)
console.log('wrote proposed-tokens.css, roles.md, preview.html')
